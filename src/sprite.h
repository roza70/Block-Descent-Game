inline void drawSaiNanami(SDL_Renderer *ren, int px, int py)
{
    for (int row = 0; row < SAI_H; row++)
    {
        for (int col = 0; col < SAI_W; col++)
        {
            int idx = SAI_SPRITE[row][col];
            if (idx == 0)
                continue;
            SDL_Color c = SAI_PALETTE[idx];
            SDL_SetRenderDrawColor(ren, c.r, c.g, c.b, c.a);
            SDL_Rect rect = {
                px + col * SAI_SCALE,
                py + row * SAI_SCALE,
                SAI_SCALE, SAI_SCALE};
            SDL_RenderFillRect(ren, &rect);
        }
    }
}